/**
 * The percolation data model of Brill & Carlson (arXiv:2606.20347), in miniature and dependency-free
 * so that it can be checked outside the browser. Nothing here simulates a lattice: criticality is
 * built in by (1) preferential attachment with p01 = 1/3 for the cluster sizes and (2) the paper's
 * cyclic coalescent (Alg. 1), an exact sampler of a uniform random labeled tree up to a relabeling (the film keeps the
 * cyclic order 0…n−1 and skips the paper's shuffle, which only renames the points) together with its
 * binary tree of merge events ("latents").
 *
 * Layout of the result: points are grouped by cluster; inside a cluster the index of a point IS its
 * position in the cyclic order (the film skips the paper's shuffle, which only renames the points).
 * Every merge creates one latent and one cluster edge, so latents and edges share an index.
 *
 * One extra cluster of a chosen size (the "demo" ring that the film animates merge by merge) is
 * appended after the preferential-attachment clusters. It goes through exactly the same coalescent,
 * target and embedding code, but it is not a draw from the size distribution, so every statistic of
 * the size distribution must be taken over the first `nPA` clusters only.
 *
 * Randomness comes from three independent groups of streams, selected by three seeds as in the paper
 * (Table 4: graph / embedding / value):
 *   graph      cluster sizes and the cyclic coalescent (cyclic order, u, v);
 *   embedding  everything that places points in R^d: cluster origins, step directions, the root point;
 *   value      the latent values z, hence the targets y.
 * Changing the value seed alone leaves every edge and every input bit-identical; changing the
 * embedding seed alone leaves every edge and every target bit-identical. The demo cluster draws from
 * its own stream of each group, so it shares no draw with the preferential-attachment clusters.
 *
 * The last section holds the choices the film makes on a generated tree (which merge it plays slowly,
 * where it cuts the demo tree, which point it follows), so that the Node checks of the chapter run
 * the same code as the page.
 */
export type Rng = () => number;

/** The three generator seeds. The chapter's URL overrides accept values from 1 to 200. */
export interface Seeds {
  graph: number;
  embedding: number;
  value: number;
}

/**
 * Seeds of the internal streams. The multi-cluster dataset uses g, 10000 + e and 20000 + v (the
 * paper's configs use 0 / 10,000 / 20,000); every other stream sits at its own offset.
 */
export function streamSeeds(u: Seeds) {
  const g = Math.round(u.graph), e = Math.round(u.embedding), v = Math.round(u.value);
  return {
    graph: g, // cluster sizes and the coalescent of the preferential-attachment clusters
    demoGraph: Math.imul(g, 7919) + 104729, // the demo tree depends on (graph seed, demoSize) only
    emb: 10000 + e, // origins and step directions
    root: 11000 + e, // random descent to the root point
    view: 12000 + e, // 3-D view only: start vectors of the PCA iteration, the fixed random projection
    demoEmb: 13000 + e,
    demoRoot: 14000 + e,
    val: 20000 + v, // latent values z
    demoVal: 21000 + v,
  };
}

/** Standard normal sampler on a private uniform stream (Box–Muller). */
function gaussOn(rnd: Rng): Rng {
  let spare = NaN;
  return () => {
    if (spare === spare) { const s = spare; spare = NaN; return s; }
    let u = 0;
    while (u === 0) u = rnd();
    const r = Math.sqrt(-2 * Math.log(u)), a = 2 * Math.PI * rnd();
    spare = r * Math.sin(a);
    return r * Math.cos(a);
  };
}

export interface GenOpts {
  n: number; // points generated by preferential attachment
  d: number; // embedding dimension
  seeds: Seeds;
  p01: number; // probability that a new point founds a new cluster (1/3 = critical mean-field percolation)
  demoSize: number; // size of the appended demo cluster (≥ 2)
  /** 'pca': each cluster in its own principal 3-frame; 'random': one fixed random orthonormal 3×d map for all */
  view: 'pca' | 'random';
}

/** The cluster graphs and their latent trees, for any number of clusters laid out one after another. */
interface Forest {
  /** the cluster edge {u, v} added by each merge (global point ids) */
  edgeU: Int32Array;
  edgeV: Int32Array;
  /** children of each latent: ≥ 0 is a latent id, < 0 is the point ~id */
  childA: Int32Array;
  childB: Int32Array;
  latParent: Int32Array; // −1 at a cluster's root
  leafParent: Int32Array; // −1 for a single-point cluster
  latDepth: Int32Array; // root = 0
  leafDepth: Int32Array; // number of latent ancestors d_x
  latSize: Int32Array; // number of points below the latent
  degree: Uint16Array; // graph degree of each point
}

function forest(n: number, nLat: number): Forest {
  return {
    edgeU: new Int32Array(nLat), edgeV: new Int32Array(nLat), childA: new Int32Array(nLat), childB: new Int32Array(nLat),
    latParent: new Int32Array(nLat).fill(-1), leafParent: new Int32Array(n).fill(-1),
    latDepth: new Int32Array(nLat), leafDepth: new Int32Array(n), latSize: new Int32Array(nLat), degree: new Uint16Array(n),
  };
}

/**
 * The cyclic coalescent (Alg. 1). Returns a function that builds one cluster of s ≥ 2 points which owns
 * points [o, o + s) and latents [lo, lo + s − 1) of F, drawing 2 (s − 1) uniforms from r.
 */
function coalescent(F: Forest, sMax: number) {
  const nxt = new Int32Array(sMax), st = new Int32Array(sMax), uf = new Int32Array(sMax);
  const rank = new Uint8Array(sMax), head = new Int32Array(sMax), rep = new Int32Array(sMax);
  const { edgeU, edgeV, childA, childB, latParent, leafParent, latSize, degree } = F;
  const find = (x: number) => {
    while (uf[x] !== x) { uf[x] = uf[uf[x]]; x = uf[x]; }
    return x;
  };
  return (s: number, o: number, lo: number, r: Rng) => {
    for (let i = 0; i < s; i++) { nxt[i] = (i + 1) % s; st[i] = 1; uf[i] = i; rank[i] = 0; head[i] = i; rep[i] = ~(o + i); }
    for (let k = 0; k < s - 1; k++) {
      const u = Math.floor(r() * s);
      const a = head[find(u)], b = nxt[a]; // b: head of the cyclic successor block
      const v = (b + Math.floor(r() * st[b])) % s; // uniform node of the successor (blocks are contiguous arcs)
      const L = lo + k;
      edgeU[L] = o + u; edgeV[L] = o + v;
      degree[o + u]++; degree[o + v]++;
      const ra = rep[a], rb = rep[b];
      childA[L] = ra; childB[L] = rb;
      if (ra >= 0) latParent[ra] = L; else leafParent[~ra] = L;
      if (rb >= 0) latParent[rb] = L; else leafParent[~rb] = L;
      latSize[L] = (ra >= 0 ? latSize[ra] : 1) + (rb >= 0 ? latSize[rb] : 1);
      rep[a] = L;
      st[a] += st[b]; nxt[a] = nxt[b];
      let x = find(u), y = find(v);
      if (rank[x] < rank[y]) { const t = x; x = y; y = t; }
      uf[y] = x;
      if (rank[x] === rank[y]) rank[x]++;
      head[x] = a;
    }
  };
}

/**
 * Depths, latent values and the targets of eq. (4) for latents [l0, l1) and points [p0, p1) (whole
 * clusters). Draws one z per latent, from the last latent down (parents have larger indices than their
 * children), then one z per point. `acc` is scratch of the size of the latent arrays.
 */
function assignTargets(F: Forest, zLat: Float32Array, zLeaf: Float32Array, y: Float32Array, acc: Float64Array,
  l0: number, l1: number, p0: number, p1: number, gauss: Rng) {
  const { latParent, leafParent, latDepth, leafDepth } = F;
  for (let L = l1 - 1; L >= l0; L--) {
    const p = latParent[L];
    zLat[L] = gauss();
    latDepth[L] = p < 0 ? 0 : latDepth[p] + 1;
    acc[L] = zLat[L] + (p < 0 ? 0 : acc[p]); // running sum of z from the root down to (and including) the latent
  }
  for (let i = p0; i < p1; i++) {
    const p = leafParent[i];
    zLeaf[i] = gauss();
    leafDepth[i] = p < 0 ? 0 : latDepth[p] + 1;
    y[i] = (zLeaf[i] + (p < 0 ? 0 : acc[p])) / Math.sqrt(1 + leafDepth[i]);
  }
}

/**
 * The embedding of one cluster: a branching random walk in R^d. Step directions are assigned down the
 * latent tree: the root latent gets a uniform unit vector, and a latent with direction v gives its
 * children (v ± w)/√2 with w ⊥ v a random unit vector, so sibling steps are orthogonal. The root point is
 * found by walking down the latent tree, choosing a child with probability 1/2 at each latent. It sits
 * one step from the origin; every other point is its graph neighbor's position plus one step along its
 * own direction.
 *
 * Returns a function that writes the walk of a cluster of s ≥ 2 points (points [o, o + s), latents
 * [lo, lo + s − 1) of F) into xc (s × d, in units of one step, origin 0, not centered). It draws s·d
 * normals from `gauss` and one uniform per level of the descent from `rRoot`.
 */
function walker(F: Forest, sMax: number, d: number) {
  const { edgeU, edgeV, childA, childB } = F;
  const vLat = new Float64Array(Math.max(1, sMax - 1) * d); // direction of each latent of the current cluster
  const vLeaf = new Float64Array(sMax * d); // step direction of each point of the current cluster
  const adjStart = new Int32Array(sMax + 1), adj = new Int32Array(2 * sMax), fill = new Int32Array(sMax);
  const stack = new Int32Array(sMax), seen = new Uint8Array(sMax);
  const tmp = new Float64Array(d);
  return (s: number, o: number, lo: number, xc: Float64Array, gauss: Rng, rRoot: Rng) => {
    // base direction of the cluster = direction of its root latent
    let nn = 0;
    for (let j = 0; j < d; j++) { tmp[j] = gauss(); nn += tmp[j] * tmp[j]; }
    nn = Math.sqrt(nn);
    const root = s - 2;
    for (let j = 0; j < d; j++) vLat[root * d + j] = tmp[j] / nn;
    for (let k = s - 2; k >= 0; k--) {
      const L = lo + k, vo = k * d;
      let dt = 0;
      for (let j = 0; j < d; j++) { tmp[j] = gauss(); dt += tmp[j] * vLat[vo + j]; }
      nn = 0;
      for (let j = 0; j < d; j++) { tmp[j] -= dt * vLat[vo + j]; nn += tmp[j] * tmp[j]; }
      nn = Math.SQRT1_2 / Math.sqrt(nn);
      const ca = childA[L], cb = childB[L];
      const da = ca >= 0 ? vLat : vLeaf, oa = (ca >= 0 ? ca - lo : ~ca - o) * d;
      const db = cb >= 0 ? vLat : vLeaf, ob = (cb >= 0 ? cb - lo : ~cb - o) * d;
      for (let j = 0; j < d; j++) {
        const v = vLat[vo + j] * Math.SQRT1_2, w = tmp[j] * nn;
        da[oa + j] = v + w;
        db[ob + j] = v - w;
      }
    }
    // random root point: walk down the latent tree, choosing a child at random
    let node = lo + root;
    while (node >= 0) node = rRoot() < 0.5 ? childA[node] : childB[node];
    const rootPt = ~node - o;
    // adjacency lists (CSR) of the cluster graph
    adjStart.fill(0, 0, s + 1);
    for (let k = 0; k < s - 1; k++) { adjStart[edgeU[lo + k] - o + 1]++; adjStart[edgeV[lo + k] - o + 1]++; }
    for (let i = 0; i < s; i++) { adjStart[i + 1] += adjStart[i]; fill[i] = adjStart[i]; seen[i] = 0; }
    for (let k = 0; k < s - 1; k++) {
      const u = edgeU[lo + k] - o, v = edgeV[lo + k] - o;
      adj[fill[u]++] = v; adj[fill[v]++] = u;
    }
    // depth-first walk: x_child = x_parent + (one step along the child's own direction)
    for (let j = 0; j < d; j++) xc[rootPt * d + j] = vLeaf[rootPt * d + j];
    let sp = 0;
    stack[sp++] = rootPt; seen[rootPt] = 1;
    while (sp > 0) {
      const p = stack[--sp];
      for (let e = adjStart[p]; e < adjStart[p + 1]; e++) {
        const q = adj[e];
        if (seen[q]) continue;
        seen[q] = 1;
        for (let j = 0; j < d; j++) xc[q * d + j] = xc[p * d + j] + vLeaf[q * d + j];
        stack[sp++] = q;
      }
    }
  };
}

export interface PercolationData extends Forest {
  /** total number of points, including the demo cluster */
  n: number;
  d: number;
  /** total number of clusters, including the demo cluster (the last one) */
  nClusters: number;
  /** number of clusters produced by preferential attachment; the demo cluster has index nPA */
  nPA: number;
  demo: number;
  /** cluster c owns points [off[c], off[c] + size[c]) */
  off: Int32Array;
  size: Int32Array;
  clusterOf: Int32Array;
  /** cluster c owns latents (= edges) [latOff[c], latOff[c] + size[c] − 1), in merge order */
  latOff: Int32Array;
  nLat: number;
  zLat: Float32Array;
  zLeaf: Float32Array;
  /** regression target of each point, eq. (4): sum of z along the root→leaf path / sqrt(1 + d_x) */
  y: Float32Array;
  /** each point's offset from its cluster centroid in the cluster's own principal 3-frame, in walk steps */
  rel: Float32Array;
  /** three coordinates of each cluster origin (origins are uniform in the unit d-ball) */
  origin: Float32Array;
  /** index of the largest cluster */
  largest: number;
}

export function generate(opt: GenOpts, mk: (seed: number) => Rng): PercolationData {
  const { d, p01 } = opt;
  const nPts = Math.max(2, Math.floor(opt.n)), demoSize = Math.max(2, Math.floor(opt.demoSize));
  const S = streamSeeds(opt.seeds);
  const rnd = mk(S.graph), rndDemo = mk(S.demoGraph); // graph
  const gE = gaussOn(mk(S.emb)), rRoot = mk(S.root), gEDemo = gaussOn(mk(S.demoEmb)), rRootDemo = mk(S.demoRoot); // embedding
  const gView = gaussOn(mk(S.view));
  const gV = gaussOn(mk(S.val)), gVDemo = gaussOn(mk(S.demoVal)); // value

  // ── 1. cluster sizes by preferential attachment ─────────────────────────────────────────────
  const first = new Int32Array(nPts); // cluster of each point in arrival order
  let nPA = 0;
  for (let i = 0; i < nPts; i++) {
    if (i === 0 || rnd() < p01) first[i] = nPA++;
    else first[i] = first[Math.floor(rnd() * i)];
  }
  const nClusters = nPA + 1, demo = nPA, n = nPts + demoSize;
  const size = new Int32Array(nClusters);
  for (let i = 0; i < nPts; i++) size[first[i]]++;
  size[demo] = demoSize;
  const off = new Int32Array(nClusters + 1);
  const latOff = new Int32Array(nClusters + 1);
  let largest = 0;
  for (let c = 0; c < nClusters; c++) {
    off[c + 1] = off[c] + size[c];
    latOff[c + 1] = latOff[c] + size[c] - 1;
    if (c < nPA && size[c] > size[largest]) largest = c;
  }
  const nLat = latOff[nClusters];
  const clusterOf = new Int32Array(n);
  for (let c = 0; c < nClusters; c++) for (let i = off[c]; i < off[c + 1]; i++) clusterOf[i] = c;

  // ── 2. cyclic coalescent, cluster by cluster ────────────────────────────────────────────────
  const sMax = Math.max(size[largest], demoSize);
  const F = forest(n, nLat);
  const coalesce = coalescent(F, sMax);
  for (let c = 0; c < nClusters; c++) if (size[c] >= 2) coalesce(size[c], off[c], latOff[c], c === demo ? rndDemo : rnd);

  // ── 3. depths, latent values and targets ────────────────────────────────────────────────────
  const zLat = new Float32Array(nLat), zLeaf = new Float32Array(n), y = new Float32Array(n);
  const acc = new Float64Array(nLat);
  assignTargets(F, zLat, zLeaf, y, acc, 0, latOff[demo], 0, off[demo], gV);
  assignTargets(F, zLat, zLeaf, y, acc, latOff[demo], nLat, off[demo], n, gVDemo);

  // ── 4. embedding: a branching random walk in R^d (see `walker`) ─────────────────────────────
  // The walk lives in R^d (fractal dimension 4 > 3), so any 3-D picture is a shadow. With view 'pca'
  // each cluster is reported in the orthonormal frame of its own three principal directions, i.e. its
  // most informative 3-D shadow; with view 'random' one fixed random orthonormal 3×d map is used for
  // every cluster. Offsets are measured from the cluster centroid in units of one step.
  const pca = opt.view !== 'random';
  const rel = new Float32Array(n * 3), origin = new Float32Array(nClusters * 3);
  const walk = walker(F, sMax, d);
  const xc = new Float64Array(sMax * d); // d-dim offsets of the current cluster
  const tmp = new Float64Array(d + 2), mean = new Float64Array(d);
  const cov = new Float64Array(d * d), Q = new Float64Array(3 * d), W = new Float64Array(3 * d);
  const orthonormalize = (V: Float64Array) => {
    for (let r = 0; r < 3; r++) {
      for (let pass = 0; pass < 2; pass++)
        for (let q = 0; q < r; q++) {
          let dt = 0;
          for (let j = 0; j < d; j++) dt += V[r * d + j] * V[q * d + j];
          for (let j = 0; j < d; j++) V[r * d + j] -= dt * V[q * d + j];
        }
      let nn = 0;
      for (let j = 0; j < d; j++) nn += V[r * d + j] * V[r * d + j];
      if (nn < 1e-18) { // degenerate direction (tiny cluster): any orthogonal vector will do
        for (let j = 0; j < d; j++) V[r * d + j] = gView();
        r--;
        continue;
      }
      nn = 1 / Math.sqrt(nn);
      for (let j = 0; j < d; j++) V[r * d + j] *= nn;
    }
  };
  const Pfix = new Float64Array(3 * d);
  for (let j = 0; j < 3 * d; j++) Pfix[j] = gView();
  orthonormalize(Pfix);
  for (let c = 0; c < nClusters; c++) {
    const s = size[c], o = off[c], lo = latOff[c];
    const g = c === demo ? gEDemo : gE;
    // origin: uniform in the unit d-ball = first d coordinates of a uniform point on S^(d+1); keep 3 of them
    let nn = 0;
    for (let j = 0; j < d + 2; j++) { tmp[j] = g(); nn += tmp[j] * tmp[j]; }
    nn = Math.sqrt(nn);
    for (let r = 0; r < 3; r++) origin[c * 3 + r] = tmp[r] / nn;
    if (s === 1) continue; // a single point sits at its origin
    walk(s, o, lo, xc, g, c === demo ? rRootDemo : rRoot);
    // center on the centroid
    mean.fill(0);
    for (let i = 0; i < s; i++) for (let j = 0; j < d; j++) mean[j] += xc[i * d + j];
    for (let j = 0; j < d; j++) mean[j] /= s;
    for (let i = 0; i < s; i++) for (let j = 0; j < d; j++) xc[i * d + j] -= mean[j];
    // 3-frame of the view
    if (!pca) Q.set(Pfix);
    else if (s <= 4) {
      // at most three independent offsets: their span is the whole cluster
      for (let r = 0; r < 3; r++) for (let j = 0; j < d; j++) Q[r * d + j] = r < s - 1 ? xc[r * d + j] : gView();
      orthonormalize(Q);
    } else {
      cov.fill(0);
      for (let i = 0; i < s; i++) {
        const xo = i * d;
        for (let p = 0; p < d; p++) {
          const xp = xc[xo + p], co = p * d;
          for (let q = p; q < d; q++) cov[co + q] += xp * xc[xo + q];
        }
      }
      for (let p = 0; p < d; p++) for (let q = 0; q < p; q++) cov[p * d + q] = cov[q * d + p];
      for (let j = 0; j < 3 * d; j++) Q[j] = gView();
      orthonormalize(Q);
      const iters = s < 40 ? 14 : s < 400 ? 40 : 120; // orthogonal (subspace) iteration
      for (let it = 0; it < iters; it++) {
        for (let r = 0; r < 3; r++)
          for (let p = 0; p < d; p++) {
            let a = 0;
            const co = p * d, ro = r * d;
            for (let q = 0; q < d; q++) a += cov[co + q] * Q[ro + q];
            W[ro + p] = a;
          }
        Q.set(W);
        orthonormalize(Q);
      }
    }
    // project, then order the three axes by variance (Rayleigh–Ritz on the 3×3 covariance)
    let b00 = 0, b01 = 0, b02 = 0, b11 = 0, b12 = 0, b22 = 0;
    for (let i = 0; i < s; i++) {
      let y0 = 0, y1 = 0, y2 = 0;
      const xo = i * d;
      for (let j = 0; j < d; j++) { const x = xc[xo + j]; y0 += Q[j] * x; y1 += Q[d + j] * x; y2 += Q[2 * d + j] * x; }
      const ro = (o + i) * 3;
      rel[ro] = y0; rel[ro + 1] = y1; rel[ro + 2] = y2;
      b00 += y0 * y0; b01 += y0 * y1; b02 += y0 * y2; b11 += y1 * y1; b12 += y1 * y2; b22 += y2 * y2;
    }
    if (!pca) continue;
    const E = eig3(b00, b01, b02, b11, b12, b22);
    for (let i = 0; i < s; i++) {
      const ro = (o + i) * 3;
      const y0 = rel[ro], y1 = rel[ro + 1], y2 = rel[ro + 2];
      rel[ro] = E[0] * y0 + E[1] * y1 + E[2] * y2;
      rel[ro + 1] = E[3] * y0 + E[4] * y1 + E[5] * y2;
      rel[ro + 2] = E[6] * y0 + E[7] * y1 + E[8] * y2;
    }
  }

  return { n, d, nClusters, nPA, demo, off, size, clusterOf, latOff, nLat, ...F, zLat, zLeaf, y, rel, origin, largest };
}

/** Eigenvectors (rows, by descending eigenvalue, right-handed) of a symmetric 3×3 matrix; Jacobi rotations. */
function eig3(a00: number, a01: number, a02: number, a11: number, a12: number, a22: number) {
  const a = [a00, a01, a02, a01, a11, a12, a02, a12, a22];
  const v = [1, 0, 0, 0, 1, 0, 0, 0, 1];
  for (let sweep = 0; sweep < 12; sweep++)
    for (let p = 0; p < 3; p++)
      for (let q = p + 1; q < 3; q++) {
        const apq = a[p * 3 + q];
        if (Math.abs(apq) < 1e-300) continue;
        const th = (a[q * 3 + q] - a[p * 3 + p]) / (2 * apq);
        const t = Math.sign(th || 1) / (Math.abs(th) + Math.sqrt(th * th + 1));
        const c = 1 / Math.sqrt(t * t + 1), s = t * c;
        for (let k = 0; k < 3; k++) {
          const akp = a[k * 3 + p], akq = a[k * 3 + q];
          a[k * 3 + p] = c * akp - s * akq; a[k * 3 + q] = s * akp + c * akq;
        }
        for (let k = 0; k < 3; k++) {
          const apk = a[p * 3 + k], aqk = a[q * 3 + k];
          a[p * 3 + k] = c * apk - s * aqk; a[q * 3 + k] = s * apk + c * aqk;
        }
        for (let k = 0; k < 3; k++) {
          const vkp = v[k * 3 + p], vkq = v[k * 3 + q];
          v[k * 3 + p] = c * vkp - s * vkq; v[k * 3 + q] = s * vkp + c * vkq;
        }
      }
  const order = [0, 1, 2].sort((i, j) => a[j * 4] - a[i * 4]);
  const E = new Float64Array(9);
  for (let r = 0; r < 3; r++) for (let k = 0; k < 3; k++) E[r * 3 + k] = v[k * 3 + order[r]];
  // keep the frame right-handed: third row = first × second
  E[6] = E[1] * E[5] - E[2] * E[4];
  E[7] = E[2] * E[3] - E[0] * E[5];
  E[8] = E[0] * E[4] - E[1] * E[3];
  return E;
}

/** Empirical complementary CDF of the cluster sizes: one sample per distinct size, P(S ≥ s). */
export function sizeCCDF(size: Int32Array) {
  const sorted = Array.from(size).sort((a, b) => a - b);
  const m = sorted.length;
  const s: number[] = [], p: number[] = [];
  for (let i = 0; i < m; i++) {
    if (i > 0 && sorted[i] === sorted[i - 1]) continue;
    s.push(sorted[i]);
    p.push((m - i) / m);
  }
  return { s, p };
}

/**
 * One cluster's merge history in local numbering: point p of the cyclic order is node p, the latent
 * created by merge j is node s + j (so the root is node 2s − 2). Every block is a contiguous arc of the
 * cyclic order, described by `start` and `cnt`.
 */
export interface ClusterTree {
  s: number;
  m: number; // merges = latents = edges = s − 1
  eu: Int32Array; // per merge: the drawn node u (position in the cyclic order)
  ev: Int32Array; // per merge: the node v of the successor block that u is joined to
  ca: Int32Array; // per merge: root node of u's block before the merge
  cb: Int32Array; // per merge: root node of the successor block
  par: Int32Array; // per node (−1 at the root)
  depth: Int32Array; // per node: number of latent ancestors
  start: Int32Array; // per node: first position of its arc
  cnt: Int32Array; // per node: number of points below
}

export function clusterTree(D: PercolationData, c: number): ClusterTree {
  const s = D.size[c], m = s - 1, o = D.off[c], lo = D.latOff[c];
  const eu = new Int32Array(m), ev = new Int32Array(m), ca = new Int32Array(m), cb = new Int32Array(m);
  const N = Math.max(1, 2 * s - 1);
  const par = new Int32Array(N).fill(-1), depth = new Int32Array(N), start = new Int32Array(N), cnt = new Int32Array(N);
  const loc = (g: number) => (g >= 0 ? s + (g - lo) : ~g - o);
  for (let p = 0; p < s; p++) { start[p] = p; cnt[p] = 1; }
  for (let j = 0; j < m; j++) {
    const L = lo + j, a = loc(D.childA[L]), b = loc(D.childB[L]);
    eu[j] = D.edgeU[L] - o; ev[j] = D.edgeV[L] - o;
    ca[j] = a; cb[j] = b;
    par[a] = s + j; par[b] = s + j;
    start[s + j] = start[a];
    cnt[s + j] = cnt[a] + cnt[b];
  }
  for (let node = N - 2; node >= 0; node--) depth[node] = depth[par[node]] + 1; // parents have larger ids
  return { s, m, eu, ev, ca, cb, par, depth, start, cnt };
}

/**
 * Cut the latent tree at every depth k = 0..kCap. The families at depth k are the nodes of depth k
 * (each owning the points below it) plus the points shallower than k (already isolated).
 * Colors are indices into a small palette: the larger child of a latent inherits its color, the
 * smaller child takes a different one, so a family keeps its hue while pieces split off it.
 * When `groups` is smaller than `hues`, palette entries with the same index modulo `groups` form a color family.
 * Siblings use different color families.
 */
export interface FamilyTable {
  kCap: number;
  col: Uint8Array; // per node
  leaf: Uint8Array; // (kCap + 1) × s: color of point p at cut depth k
  edge: Uint8Array; // (kCap + 1) × m: color of edge j at cut depth k, 255 = cut
  count: Int32Array; // per k: number of families
  largest: Int32Array; // per k: size of the largest family
  alone: Int32Array; // per k: number of isolated points (families of size one)
}

export function familyTable(T: ClusterTree, kCapWanted: number, hues: number, groups = hues): FamilyTable {
  const { s, m, par, depth, cnt, ca, cb } = T;
  const N = Math.max(1, 2 * s - 1);
  let maxDepth = 0;
  for (let p = 0; p < s; p++) if (depth[p] > maxDepth) maxDepth = depth[p];
  const kCap = Math.max(0, Math.min(Math.floor(kCapWanted), maxDepth));
  const col = new Uint8Array(N);
  // Offsets give the split-off piece a different color family from the child that inherits the parent's color.
  const offs: number[] = [];
  for (let o = 1; o < hues; o++) if (o % groups !== 0) offs.push(o);
  if (!offs.length) offs.push(1);
  for (let j = m - 1; j >= 0; j--) {
    const a = ca[j], b = cb[j], c = col[s + j];
    const big = cnt[a] >= cnt[b] ? a : b, small = big === a ? b : a;
    col[big] = c;
    col[small] = (c + offs[(Math.imul(small + 1, 0x9e3779b1) >>> 8) % offs.length]) % hues;
  }
  const K1 = kCap + 1;
  const leaf = new Uint8Array(K1 * s), edge = new Uint8Array(K1 * Math.max(1, m));
  for (let p = 0; p < s; p++) {
    let node = p, dd = depth[p];
    for (let k = kCap; k >= 0; k--) {
      while (dd > k) { node = par[node]; dd--; }
      leaf[k * s + p] = col[node];
    }
  }
  for (let j = 0; j < m; j++) {
    let node = s + j, dd = depth[node];
    for (let k = kCap; k >= 0; k--) {
      if (k > dd) { edge[k * m + j] = 255; continue; }
      while (dd > k) { node = par[node]; dd--; }
      edge[k * m + j] = col[node];
    }
  }
  const count = new Int32Array(K1), largest = new Int32Array(K1), alone = new Int32Array(K1);
  const atDepth = new Int32Array(maxDepth + 2), leavesAt = new Int32Array(maxDepth + 2), bigAt = new Int32Array(maxDepth + 2);
  for (let node = 0; node < N; node++) {
    const dd = depth[node];
    atDepth[dd]++;
    if (node < s) leavesAt[dd]++;
    if (cnt[node] > bigAt[dd]) bigAt[dd] = cnt[node];
  }
  let shallow = 0; // points with depth < k
  for (let k = 0; k <= kCap; k++) {
    count[k] = atDepth[k] + shallow;
    alone[k] = shallow + leavesAt[k];
    largest[k] = Math.max(1, bigAt[k]);
    shallow += leavesAt[k];
  }
  return { kCap, col, leaf, edge, count, largest, alone };
}

/** log Γ(x) for x > 0 (Lanczos, g = 7). */
export function lgamma(x: number): number {
  const g = [0.99999999999980993, 676.5203681218851, -1259.1392167224028, 771.32342877765313, -176.61502916214059,
    12.507343278686905, -0.13857109526572012, 9.9843695780195716e-6, 1.5056327351493116e-7];
  if (x < 0.5) return Math.log(Math.PI / Math.sin(Math.PI * x)) - lgamma(1 - x);
  x -= 1;
  let a = g[0];
  const t = x + 7.5;
  for (let i = 1; i < 9; i++) a += g[i] / (x + i);
  return 0.5 * Math.log(2 * Math.PI) + (x + 0.5) * Math.log(t) - t + Math.log(a);
}

/** Yule–Simon law, the stationary size distribution of preferential attachment: P(S ≥ s) = Γ(s) Γ(ρ+1) / Γ(s+ρ). */
export const yuleSimonCCDF = (s: number, rho: number) => Math.exp(lgamma(s) + lgamma(rho + 1) - lgamma(s + rho));

/**
 * Fit the Yule–Simon parameter ρ to all cluster sizes using P(S = s) = ρ B(s, ρ + 1).
 * The fitted survival curve decays as s^(−ρ) at large sizes.
 */
export function fitYuleSimon(size: Int32Array) {
  // sufficient statistic: histogram of sizes
  const hist = new Map<number, number>();
  for (let i = 0; i < size.length; i++) hist.set(size[i], (hist.get(size[i]) ?? 0) + 1);
  const ks = Array.from(hist.keys()), ws = ks.map((k) => hist.get(k)!);
  const m = size.length;
  const ll = (rho: number) => {
    let a = m * (Math.log(rho) + lgamma(rho + 1));
    for (let i = 0; i < ks.length; i++) a += ws[i] * (lgamma(ks[i]) - lgamma(ks[i] + rho + 1));
    return a;
  };
  // golden-section search on a bracket that covers every p01 in (0, 0.9)
  let lo = 0.3, hi = 12;
  const gr = (Math.sqrt(5) - 1) / 2;
  let x1 = hi - gr * (hi - lo), x2 = lo + gr * (hi - lo), f1 = ll(x1), f2 = ll(x2);
  for (let it = 0; it < 60; it++) {
    if (f1 < f2) { lo = x1; x1 = x2; f1 = f2; x2 = lo + gr * (hi - lo); f2 = ll(x2); }
    else { hi = x2; x2 = x1; f2 = f1; x1 = hi - gr * (hi - lo); f1 = ll(x1); }
  }
  return (lo + hi) / 2;
}

