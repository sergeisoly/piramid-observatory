/**
 * Where the film cuts the demo tree: the shallowest depth kd at which four or more latents own two points or
 * more (failing that, the depth with the most such latents), and latent A, the largest latent at that depth.
 */
export function demoCut(T: ClusterTree): { kd: number; A: number; maxDepth: number } {
  const { s, depth, cnt } = T, N = 2 * s - 1;
  let maxDepth = 1;
  for (let p = 0; p < s; p++) maxDepth = Math.max(maxDepth, depth[p]);
  let kd = -1, bestK = 1, bestN = -1;
  for (let k = 1; k < maxDepth && kd < 0; k++) {
    let c = 0;
    for (let node = s; node < N; node++) if (depth[node] === k && cnt[node] >= 2) c++;
    if (c >= 4) kd = k;
    if (c > bestN) { bestN = c; bestK = k; }
  }
  if (kd < 0) kd = bestK;
  let A = -1;
  for (let node = s; node < N; node++) if (depth[node] === kd && (A < 0 || cnt[node] > cnt[A])) A = node;
  if (A < 0) { A = N - 1; kd = 0; }
  return { kd, A, maxDepth };
}

/**
 * The merge the film plays slowly: the first that joins two groups of two points or more, so that both random
 * choices have more than one point to choose from (the first merges of a ring join single points), and whose two
 * points are not neighbors on the ring, so that the line it adds can be seen. Failing that, the first that joins
 * two such groups, then the first whose next group has two points or more, else the first merge.
 */
export function slowMerge(T: ClusterTree): number {
  const { s, m, ca, cb, cnt, eu, ev } = T;
  for (let j = 0; j < m; j++) if (cnt[ca[j]] >= 2 && cnt[cb[j]] >= 2 && (ev[j] - eu[j] + s) % s >= 2) return j;
  for (let j = 0; j < m; j++) if (cnt[ca[j]] >= 2 && cnt[cb[j]] >= 2) return j;
  for (let j = 0; j < m; j++) if (cnt[cb[j]] >= 2) return j;
  return 0;
}

/**
 * The point the film follows: a point under latent A at least two depths below the cut, so that its path runs
 * through A's latent and on; of those, the one whose depth is nearest the median depth of A's points, with a
 * target far enough from 0 to draw (|y| ≥ 0.3 where possible). `y` and `off` locate the cluster's targets.
 * Failing that, the deepest point under A.
 */
export function markedPoint(T: ClusterTree, A: number, kd: number, y: ArrayLike<number>, off: number): number {
  const { s, par, depth } = T;
  const under: number[] = [];
  for (let p = 0; p < s; p++) { let x = p; while (x >= 0 && x !== A) x = par[x]; if (x === A) under.push(p); }
  const dep = under.map((p) => depth[p]).sort((a, b) => a - b), med = dep[dep.length >> 1];
  let pick = -1, best = Infinity;
  for (const p of under) {
    if (depth[p] < kd + 2) continue;
    const cost = Math.abs(depth[p] - med) + (Math.abs(y[off + p]) < 0.3 ? 5 : 0);
    if (cost < best) { best = cost; pick = p; }
  }
  if (pick < 0) for (const p of under) if (pick < 0 || depth[p] > depth[pick]) pick = p;
  return pick < 0 ? 0 : pick;
}

/**
 * The depth at which the film cuts the largest cluster, so that its subclusters visibly come in every size: of the
 * depths from 8 to kCap at which they range from a single point to 100 points or more, the one with the most
 * subclusters of two points or more. Failing that, the depth with the most such subclusters.
 */
export function heroCut(T: ClusterTree, kCap: number): number {
  const { s, depth, cnt } = T, N = 2 * s - 1, K = Math.max(0, kCap) + 1;
  const n2 = new Int32Array(K), one = new Uint8Array(K), big = new Int32Array(K);
  for (let node = 0; node < N; node++) {
    const k = depth[node];
    if (k >= K) continue;
    if (cnt[node] >= 2) n2[k]++;
    if (cnt[node] === 1) one[k] = 1;
    if (cnt[node] > big[k]) big[k] = cnt[node];
  }
  let kb = -1;
  for (let k = Math.min(8, K - 1); k < K; k++) if (one[k] && big[k] >= 100 && (kb < 0 || n2[k] > n2[kb])) kb = k;
  if (kb < 0) for (let k = Math.min(8, K - 1); k < K; k++) if (kb < 0 || n2[k] > n2[kb]) kb = k;
  return Math.max(0, kb);
}
