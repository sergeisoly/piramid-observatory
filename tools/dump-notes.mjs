// Export numbered notes, authored details and end-card sources as Markdown alongside the presentation script.
//   node tools/dump-notes.mjs --url=http://127.0.0.1:5199 --out=../review/notes.md
import { launchChrome } from './browser.mjs';
import { readFlags } from './flags.mjs';
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const args = readFlags();
const base = args.url ?? 'http://127.0.0.1:5199', out = resolve(args.out ?? 'review/story/notes.md');
const browser = await launchChrome({ chrome: args.chrome });
try {
  const page = await browser.newPage();
  await page.goto(`${base}/?shot=1&ch=prologue&t=0`, { waitUntil: 'load' });
  await page.waitForFunction('window.__shotReady === true', { timeout: 180000 });
  // A chapter may place its markers from the camera of its last rendered frame (chapter 1 does), so each
  // moment is posed and rendered before its notes are read; reading inspect() without a frame misses them.
  const data = await page.evaluate(async () => {
    const e = window.__piramid;
    e.playing = false;
    const frame = (n = 2) => new Promise((ok) => { const f0 = e.frames; const w = () => (e.frames - f0 >= n ? ok() : requestAnimationFrame(w)); w(); });
    const plain = (h) => { const d = document.createElement('div'); d.innerHTML = h.replace(/<\/p>\s*<p>/g, '</p>\n\n<p>'); return d.textContent.trim(); };
    const row = (r) => `- ${plain(r.label)}: ${plain(r.value)}${r.note ? ` (${plain(r.note)})` : ''}`;
    const out = [];
    for (const [i, c] of e.chapters.entries()) {
      const details = new Map(); // optional authored prose can change between slides
      const notes = new Map();
      for (let t = 0; t < c.duration; t += 0.5) {
        e.seek(e.starts[i] + t);
        await frame();
        const detail = c.details?.(t);
        if (detail) {
          const key = JSON.stringify(detail);
          if (!details.has(key)) details.set(key, { t, title: plain(detail.title), body: plain(detail.body) });
        }
        for (const h of c.inspect?.(t) ?? []) if (!notes.has(h.id)) notes.set(h.id, { t, title: plain(h.title), body: plain(h.body), rows: (h.rows ?? []).map(row) });
      }
      out.push({ n: String(i).padStart(2, '0'), title: c.title, details: [...details.values()], sources: (c.endSources ?? []).map(row), notes: [...notes.values()], results: (c.results ?? []).map((r) => `- [${r.group ?? '-'}${r.headline ? ', headline' : ''}] ${plain(r.label)}: ${plain(r.measured)} · reference: ${plain(r.reference)}${r.say ? ` · board: ${plain(r.say)}` : ''}`) });
    }
    return out;
  });
  let md = '# PIRAMID Observatory: the text beside the slides\n\nGenerated by `tools/dump-notes.mjs` from the running film: the numbered notes, optional authored details, end-card sources and results each chapter reports to the closing board.\n';
  for (const c of data) {
    md += `\n## ${c.n} ${c.title}\n`;
    for (const detail of c.details) md += `\n### ${detail.title} (first shown at ${detail.t.toFixed(1)} s)\n\n${detail.body}\n`;
    if (c.sources.length) md += `\n### End-card sources\n\n${c.sources.join('\n')}\n`;
    for (const n of c.notes) md += `\n### Note: ${n.title} (first shown at ${n.t.toFixed(1)} s)\n\n${n.body}\n${n.rows.length ? '\n' + n.rows.join('\n') + '\n' : ''}`;
    if (c.results.length) md += `\n### Results reported\n\n${c.results.join('\n')}\n`;
  }
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, md);
  console.log('saved', out, md.split(/\s+/).length, 'words');
} finally {
  await browser.close();
}
